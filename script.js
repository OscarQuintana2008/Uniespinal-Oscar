/* CAMBIO DE IDIOMA */
const DICCIONARIOS = {
  es: ES,
  en: EN
};

let idiomaActual = "es";

function aplicarIdioma(idioma) {
  const textos = DICCIONARIOS[idioma];

  if (!textos) return;

  document.querySelectorAll("[data-i18n]").forEach(elemento => {
    const clave = elemento.getAttribute("data-i18n");

    if (textos[clave] !== undefined) {
      elemento.textContent = textos[clave];
    } else {
      console.warn("Missing translation key:", clave);
    }
  });

  document.documentElement.lang = idioma;

  const boton = document.getElementById("btn-idioma");

  if (boton) {
    const otro = idioma === "es" ? "en" : "es";

    boton.innerHTML =
      '<span class="idioma-activo">' +
      idioma.toUpperCase() +
      "</span>" +
      '<span class="idioma-sep">/</span>' +
      '<span class="idioma-inactivo">' +
      otro.toUpperCase() +
      "</span>";

    boton.setAttribute(
      "aria-label",
      idioma === "es" ? "Switch to English" : "Cambiar a español"
    );
  }

  idiomaActual = idioma;
}

function cambiarIdioma() {
  aplicarIdioma(idiomaActual === "es" ? "en" : "es");
}

/* MENÚ PARA CELULAR */
let menuVisible = false;

function mostrarOcultarMenu() {
  const nav = document.getElementById("nav");

  if (!nav) return;

  menuVisible = !menuVisible;
  nav.classList.toggle("responsive", menuVisible);
}

function cerrarMenu() {
  const nav = document.getElementById("nav");

  if (nav) {
    nav.classList.remove("responsive");
  }

  menuVisible = false;
}

/* ANIMACIÓN DE LAS BARRAS DE HABILIDADES */
function animarHabilidades() {
  const barras = document.querySelectorAll(".progreso");

  const mostrar = barra => {
    const porcentaje = barra.getAttribute("data-percent") || "0";

    barra.style.width = porcentaje + "%";

    const etiqueta = barra.querySelector("span");

    if (etiqueta) {
      etiqueta.textContent = porcentaje + "%";
    }
  };

  if (!("IntersectionObserver" in window)) {
    barras.forEach(mostrar);
    return;
  }

  const observador = new IntersectionObserver(
    (entradas, obs) => {
      entradas.forEach(entrada => {
        if (entrada.isIntersecting) {
          mostrar(entrada.target);
          obs.unobserve(entrada.target);
        }
      });
    },
    {
      threshold: 0.4
    }
  );

  barras.forEach(barra => {
    observador.observe(barra);
  });
}

